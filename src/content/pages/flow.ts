const COPY: Record<Locale, FlowCopy> = { en, rw, fr };
export const flowCopy = (l: Locale) => COPY[l];
/** `{name}` placeholder fill. */
export const fill = (s: string, v: Record<string, string | number>) =>
  s.replace(/\{(\w+)\}/g, (_, k) => String(v[k] ?? `{${k}}`));
