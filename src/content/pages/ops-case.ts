const ALL: Record<Locale, OpsCaseCopy> = { en, fr, rw };
export const opsCase = (l: Locale) => ALL[l];
/** "{n} items" → fill(s, { n: 2 }). */
export const fill = (s: string, v: Record<string, string | number>) =>
  s.replace(/\{(\w+)\}/g, (m, k) => (k in v ? String(v[k]) : m));
