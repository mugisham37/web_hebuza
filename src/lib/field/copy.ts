const ALL: Record<L3, FieldCopy> = { en, fr, rw };
export const fieldCopy = (l: string) => ALL[(l as L3) in ALL ? (l as L3) : "en"];
export function useFieldCopy() {
  const { locale } = useI18n();
  return { c: fieldCopy(locale), locale: locale as L3 };
}
/** "{n} pending" → fill. */
export const fill = (s: string, v: Record<string, string | number>) => s.replace(/\{(\w+)\}/g, (_, k) => String(v[k] ?? ""));
